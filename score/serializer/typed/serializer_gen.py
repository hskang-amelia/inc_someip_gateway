def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--spec", required=True)
    parser.add_argument("--types-out", required=True)
    parser.add_argument("--serializer-out", required=True)
    parser.add_argument("--types-include", required=True, help="include path of the generated types header")
    args = parser.parse_args(argv)
    try:
        spec, wire_sizes, entries = load_spec(args.spec)
    except (SpecError, json.JSONDecodeError) as e:
        print(f"serializer_gen: {e}", file=sys.stderr)
        return 1
    guard = re.sub(r"[^A-Za-z0-9]", "_", args.types_include).upper()
    with open(args.types_out, "w", encoding="utf-8") as f:
        f.write(emit_types(spec, wire_sizes, guard))
    with open(args.serializer_out, "w", encoding="utf-8") as f:
        f.write(emit_serializer(spec, entries, args.types_include))
    return 0


if __name__ == "__main__":
    sys.exit(main())
